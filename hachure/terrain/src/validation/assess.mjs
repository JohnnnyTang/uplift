/** Generate machine-readable outcomes; --require-pass is the separate scientific acceptance gate. */
import { build } from "vite";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import process from "node:process";
import console from "node:console";
await build({
  configFile: false,
  logLevel: "warn",
  build: {
    ssr: "hachure/terrain/src/validation/assessment.ts",
    outDir: "node_modules/.cache/uplift-assessment",
    minify: false,
    emptyOutDir: true,
    rollupOptions: { output: { entryFileNames: "assess.js" } },
  },
});
const { assessAll } = await import(
  pathToFileURL(resolve("node_modules/.cache/uplift-assessment/assess.js")).href
);
const arms = ["rain-low", "rain-high", "uniform", "hard-band", "slope-low", "slope-high"];
const runs = [1, 17, 101].flatMap((seed) =>
  arms.map((arm) =>
    JSON.parse(readFileSync(resolve("docs/science/validation", `seed-${seed}-${arm}.json`), "utf8")),
  ),
);
const result = assessAll(runs);
writeFileSync(resolve("docs/science/validation/summary.json"), JSON.stringify(result, null, 2) + "\n");
const status = {
  recordId: result.protocolId,
  evidencePath: "docs/science/validation/summary.json",
  expertReview: "pending",
  allQualitativeClaimsPassed: result.allQualitativeClaimsPassed,
  prediction: result.prediction,
  calibration: {
    status: result.seeds.every((seed) => seed.calibration?.status === "failed")
      ? "failed"
      : "pending-expert-review",
    approved: false,
    approver: null,
    approvedAt: null,
  },
};
writeFileSync(
  resolve("hachure/terrain/src/validation/status.ts"),
  "/** <!-- expert-review --> Generated by assess.mjs from recorded real-solver evidence. */\n" +
    "export const V_VALLEY_SCIENCE_STATUS = " +
    JSON.stringify(status, null, 2) +
    " as const;\n",
);
console.log(JSON.stringify(result, null, 2));
if (process.argv.includes("--require-pass") && !result.allQualitativeClaimsPassed) process.exitCode = 1;
