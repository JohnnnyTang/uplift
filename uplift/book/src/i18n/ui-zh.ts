export function translateDynamic(s: string, t: (s: string) => string): string | null {
  const patterns: readonly [RegExp, (...parts: string[]) => string][] = [
    [/^Lesson (\d+)(?: · (.*))?$/, (_, n, title) => `第 ${n} 课${title ? ` · ${t(title)}` : ""}`],
    [/^Fig\. (\d+)(?:: (.*))?$/, (_, n, caption) => `图 ${n}${caption ? `：${t(caption)}` : ""}`],
    [
      /^(Read|Explore|Turn to) (.+)$/,
      (_, action, title) =>
        `${action === "Read" ? "阅读" : action === "Explore" ? "探索" : "翻至"} ${t(title)}`,
    ],
    [/^Read (.+) ↗$/, (_, title) => `阅读${t(title.charAt(0).toUpperCase() + title.slice(1))} ↗`],
    [
      /^(.+), (spread|explanation|illustration)\.$/,
      (_, title, page) =>
        `${t(title)}，${page === "spread" ? "跨页" : page === "explanation" ? "解释" : "插图"}。`,
    ],
    [/^Vertical scale ×(.+)$/, (_, value) => `垂直比例 ×${value}`],
    [/^Front face, enlarged · (.+)$/, (_, scale) => `前剖面（放大） · ${t(scale)}`],
    [/^vertical ×(.+)$/, (_, scale) => `垂直 ×${scale}`],
    [/^(.+) degrees above the page$/, (_, value) => `高于书页 ${value} 度`],
    [/^(.+) degrees from centre$/, (_, value) => `偏离中心 ${value} 度`],
    [/^(.+) percent$/, (_, value) => `${value}%`],
    [/^(.+) times$/, (_, value) => `${value} 倍`],
    [/^(.+) model years$/, (_, value) => `${value} 模型年`],
    [/^(.+), run (\d+)$/, (_, name, n) => `${t(name)}，实验 ${n}`],
    [
      /^(.+) down the valley, (through the ice|below the snout)$/,
      (_, where, part) =>
        `沿河谷向下 ${where}，${part === "through the ice" ? "切穿冰体" : "位于冰舌末端下方"}`,
    ],
    [
      /^The front face of the block stands (.+) down the valley\.$/,
      (_, where) => `岩块前剖面位于沿河谷向下 ${where} 处。`,
    ],
    [
      /^Its cross-section is (.+) \(shape (.+); a V is about 1, a U about 2\)\.$/,
      (_, shape, value) => `其横剖面${t(shape)}（形状指数 ${value}；V 形约为 1，U 形约为 2）。`,
    ],
    [/^The front face stands (.+)\.$/, (_, where) => `前剖面位于${t(where)}。`],
    [/^(.+) boundary, (.+) stage\.$/, (_, boundary, stage) => `${t(boundary)}边界，${t(stage)}阶段。`],
    [/^(.+) stage$/, (_, stage) => `${t(stage)}阶段`],
    [
      /^The (dotted|dash-dot|dash-dot-dot) line on the front face is the (.+) profile at the same stage: there the land (.+)\.$/,
      (_, pattern, name, shape) => `前剖面上的${t(pattern)}为同一阶段的${t(name)}剖面：地形${t(shape)}。`,
    ],
    [/^Starting again removes the kept run\.\s*$/, () => "重新开始会删除保留的实验。 "],
    [/^Starting again removes all (\d+) kept runs\.\s*$/, (_, n) => `重新开始会删除全部 ${n} 次保留实验。 `],
    [/^\((dotted|dash-dot|dash-dot-dot)\)$/, (_, pattern) => `（${t(pattern)}）`],
    [/^(Drawing only|Simplified view): (.+)$/, (_, prefix, reason) => `${t(prefix)}：${t(reason)}`],
  ];
  // Specific compound labels precede the general patterns above.
  const read = s.match(/^Read (.+) ↗$/);
  if (read) return `阅读${t(read[1]!.charAt(0).toUpperCase() + read[1]!.slice(1))} ↗`;
  const past = s.match(/^earlier · model time (.+)$/);
  if (past) return "较早时刻 · 模型时间 " + t(past[1]!);
  const kept = s.match(/^kept run (\d+) · model time (.+)$/);
  if (kept) return "保留实验 " + kept[1] + " · 模型时间 " + t(kept[2]!);
  const live = s.match(/^model time (.+)$/);
  if (live) return `模型时间 ${t(live[1]!)}`;
  const provenance = s.match(
    /^(Live run of the glacier model|Recorded run of the glacier model), ([^.]+)\. (.+)$/,
  );
  if (provenance) return `${t(provenance[1]!)}，${t(provenance[2]!)}。${t(provenance[3]!)}`;
  for (const [pattern, render] of patterns) {
    const match = s.match(pattern);
    if (match) return render(...match);
  }
  return null;
}
